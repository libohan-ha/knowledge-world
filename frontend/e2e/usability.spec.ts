import {test,expect,password,api} from './fixtures'

test('navigation, card dialog and fixed task completion use real isolated APIs',async({page},info)=>{
  await page.goto('/rewards')
  await page.getByLabel('怎么称呼你').fill('SYNTHETIC usability')
  await page.getByLabel('账户密码').fill(password)
  await page.getByRole('button',{name:'点亮我的营地'}).click()
  await expect(page).toHaveURL(/world$/)
  await page.goto('/rewards')
  if(info.project.name==='desktop'){
    await page.getByRole('button',{name:'折叠侧边栏'}).click()
    await expect(page.locator('.app-shell')).toHaveClass(/nav-collapsed/)
    await page.reload()
    await expect(page.locator('.app-shell')).toHaveClass(/nav-collapsed/)
    await page.getByRole('button',{name:'展开侧边栏'}).click()
  }
  await expect(page.locator('link[rel=icon]')).toHaveAttribute('href','/favicon.svg')
  const reward=await api(page,'/rewards','POST',{name:'SYNTHETIC long reward',description:'摘要内容。'.repeat(80),price_points:10,duration_minutes:1})
  await page.reload()
  const card=page.locator('.reward-card').filter({has:page.getByRole('heading',{name:reward.name})})
  await card.getByRole('button',{name:'查看详情'}).click()
  await expect(card).toHaveClass(/is-expanded/)
  await card.getByRole('button',{name:'删除 '+reward.name}).click()
  const dialog=page.getByRole('dialog',{name:'删除这项奖励'})
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button',{name:'保留奖励'}).click()
  await expect(card).toBeVisible()
  await page.goto('/system?tab=fixed')
  await page.getByRole('button',{name:'添加固定任务'}).click()
  await page.getByLabel('固定任务名称').fill('SYNTHETIC 复习错题')
  await page.getByLabel('每次完成积分').fill('12')
  await page.getByRole('button',{name:'保存任务与积分'}).click()
  await page.getByRole('button',{name:'已完成，汇报'}).click()
  await expect(page.getByText(/当前可用 12 积分/)).toBeVisible()
  await page.screenshot({path:info.outputPath('fixed-tasks.png')})
})
