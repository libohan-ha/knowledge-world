      await expect(page.getByText('隔离开发 · 测试适配器已启用，AI 输出不能作为真实接入证据')).toBeVisible()
      const home=await api(page,'/world/home');expect(home.items).toHaveLength(1);expect(home.roster.monsters).toHaveLength(1)
